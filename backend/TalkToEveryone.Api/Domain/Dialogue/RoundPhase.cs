namespace TalkToEveryone.Api.Domain.Dialogue;

/// <summary>
/// Фаза игрового раунда согласно мастер-спецификации «Угадай кента» (R1–R5 и финал).
/// </summary>
public enum RoundPhase
{
    /// <summary>
    /// Раунд 1: Визитка и ред флаг (тайминг слота: 24 сек, лимит: 200 симв).
    /// </summary>
    Presentation = 1,

    /// <summary>
    /// Раунд 2: История косяка или знакомства (тайминг слота: 33 сек, лимит: 260 симв).
    /// </summary>
    Gossip = 2,

    /// <summary>
    /// Раунд 2 (Доп. запрос): Встречный вброс соседа с места (тайминг: 8 сек, лимит: 110 симв).
    /// </summary>
    GossipCounterThrow = 3,

    /// <summary>
    /// Раунд 3 (Блиц): Долги, материальный коннект и локальный мем (тайминг слота: 21 сек, лимит: 180 симв).
    /// </summary>
    Blindspots = 4,

    /// <summary>
    /// Раунд 4: Послотовый допрос от жюри (тайминг слота: 45 сек, лимит: 200 симв).
    /// </summary>
    Interrogation = 5,

    /// <summary>
    /// Раунд 5: Цепная перепалка ИИ без участия жюри (тайминг хода: 18 сек, эстафета по <c>addressing_slot</c>).
    /// </summary>
    BotCrossfire = 6,

    /// <summary>
    /// Совещание жюри и окно выбора пары после раунда.
    /// </summary>
    Choice = 7,

    /// <summary>
    /// Финал: Вскрытие пар, показ <c>shared_lore</c> и <c>hidden_thought</c>, подведение итогов (120 сек).
    /// </summary>
    Reveal = 8
}
